const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),{pathToFileURL}=require('node:url');
const {chromium}=require('playwright');
const root=path.resolve(__dirname,'..'),out=path.join(root,'evidence/editor-01'),shots=path.join(out,'screenshots');
const app=pathToFileURL(path.join(root,'Quantum-Office.html')).href;

async function main(){
 fs.mkdirSync(shots,{recursive:true});const browser=await chromium.launch(),errors=[];
 try{
  const context=await browser.newContext({offline:true,acceptDownloads:true,viewport:{width:1920,height:1080}});
  const page=await context.newPage();page.setDefaultTimeout(8000);
  page.on('pageerror',error=>errors.push(error.message));
  page.on('dialog',dialog=>dialog.accept());
  const command=name=>page.locator('[data-qw-action="'+name+'"]');
  const live=()=>page.locator('[data-bank-live=prompt]');
  const source=()=>page.locator('[data-bank-task-field=prompt]');
  const shot=name=>page.screenshot({path:path.join(shots,name+'.png')});
  await page.goto(app);
  await page.evaluate(()=>route('work'));
  await command('settings').click();
  await page.locator('[data-work-profile]').selectOption('notes');
  await page.locator('[data-meta=title]').fill('Колебания пружинного маятника');
  await command('meta-apply').click();
  await command('add').click();
  await shot('empty-editor');
  await live().fill('Свободные колебания возникают после выхода из положения равновесия.');
  const select=word=>live().evaluate((element,word)=>{
   const walker=document.createTreeWalker(element,NodeFilter.SHOW_TEXT);
   while(walker.nextNode()){
    const node=walker.currentNode,start=node.data.indexOf(word);
    if(start>=0){
     const range=document.createRange();range.setStart(node,start);range.setEnd(node,start+word.length);
     const selection=window.getSelection();selection.removeAllRanges();selection.addRange(range);return;
    }
   }
   throw new Error('Text is missing: '+word);
  },word);
  await select('Свободные');
  const floating=page.locator('.qw-editor-context');
  await floating.waitFor();
  const box=await floating.boundingBox(),selection=await page.evaluate(()=>getSelection().getRangeAt(0).getBoundingClientRect().toJSON());
  assert.ok(box.y+box.height<selection.y||box.y>selection.bottom);
  await shot('context-toolbar');
  await floating.locator('[data-editor-context=bold]').click();
  await select('Свободные');
  await page.locator('[data-editor-style=font]').selectOption('serif');
  await select('Свободные');
  await page.locator('[data-editor-style=size]').selectOption('18');
  await select('Свободные');
  await page.locator('[data-editor-style=color]').fill('#203c7b');
  await select('Свободные');
  await floating.locator('[data-editor-context=highlight]').click();
  const styleHTML=await live().innerHTML();
  for(const part of ['font=serif','size=18','color=#203c7b','highlight=#ffe396'])assert.ok(styleHTML.includes(part),styleHTML);
  await select('Свободные');
  await page.locator('[data-bank-format=clear]').click();
  assert.doesNotMatch(await source().inputValue(),/font=serif|size=18|color=#203c7b|highlight=#ffe396/);
  await page.locator('[data-bank-format=undo]').click();
  assert.match(await source().inputValue(),/font=serif size=18 color=#203c7b highlight=#ffe396/);
  await select('возникают');
  const paragraphMenu=page.locator('.qw-editor-popover').first();
  await paragraphMenu.locator('summary').click();
  await page.locator('[data-editor-style=line]').selectOption('1.5');
  await page.locator('[data-editor-style=after]').fill('9');
  await page.locator('[data-editor-style=after]').press('Tab');
  assert.match(await source().inputValue(),/^::format line=1\.5 after=9\n/);
  await paragraphMenu.locator('summary').click();
  await select('колебания');
  await floating.locator('[data-editor-context=strike]').click();
  assert.match(await source().inputValue(),/~{2}колебания~{2}/);
  await page.locator('[data-editor-scope]').selectOption('document');
  await page.locator('[data-editor-style=font]').selectOption('sans');
  await page.locator('[data-bank-format-select=align]').selectOption('left');
  await page.locator('[data-bank-format=bold]').click();
  await page.locator('[data-bank-format=bold]').click();
  await page.locator('[data-editor-scope]').selectOption('selection');
  const end=async(target=live())=>target.evaluate(element=>{
   const range=document.createRange();range.selectNodeContents(element);range.collapse(false);
   const selection=window.getSelection();selection.removeAllRanges();selection.addRange(range);
  });
  await end();
  await page.locator('[data-bank-format-select=callout]').selectOption('definition');
  const callout=live().locator('.qw-callout');
  await callout.waitFor();
  assert.equal(await callout.getAttribute('data-qw-callout'),'definition');
  await end(callout.locator('.qw-callout-body p'));
  await page.keyboard.insertText('Период — время одного полного колебания.');
  await page.locator('[data-editor-callout] summary').click();
  await page.locator('[data-callout-setting=icon]').uncheck();
  await page.locator('[data-callout-setting=background]').fill('#e4f7fb');
  await page.locator('[data-callout-setting=pad]').fill('12');
  await page.locator('[data-callout-setting=pad]').press('Tab');
  assert.equal(await callout.locator('.qw-callout-icon').count(),0);
  assert.match(await callout.getAttribute('data-qw-callout-options'),/background=#e4f7fb pad=12/);
  await page.locator('[data-editor-callout] summary').click();
  await end(callout.locator('.qw-callout-body p'));
  await page.locator('[data-bank-format-select=formula]').selectOption('fraction');
  await page.locator('[data-bank-equation-source]').fill('f=\\frac{1}{T}');
  await page.locator('[data-bank-equation-apply]').click();
  assert.equal(await callout.locator('mfrac').count(),1);
  const markup=await source().inputValue();
  assert.match(markup,/>\s+\[!definition icon=0 background=#e4f7fb pad=12\]/);
  await page.locator('[data-bank-format=undo]').click();
  assert.equal(await callout.locator('mfrac').count(),0);
  await page.locator('[data-bank-format=redo]').click();
  assert.equal(await callout.locator('mfrac').count(),1);
  await page.locator('[data-bank-source]').click();
  assert.equal(await source().inputValue(),markup);
  await page.locator('[data-bank-source]').click();
  await shot('formatted-work');
  assert.doesNotMatch(await page.locator('.qw-nav-task').textContent(),/::format|\[\[style|\[\!/);
  const saved=page.waitForEvent('download');
  await page.locator('[data-action=work-save]').click();
  const file=path.join(out,'edited.qwork');
  await (await saved).saveAs(file);
  await page.reload();await page.evaluate(()=>route('work'));
  assert.equal(await source().inputValue(),markup);
  assert.equal(await page.evaluate(()=>qwDoc.printSettings.text.font),'sans');
  assert.equal(await page.evaluate(()=>qwDoc.printSettings.text.align),'left');
  await page.locator('#qw-file').setInputFiles(file);
  await page.waitForFunction(()=>document.getElementById('toast')?.textContent.includes('Работа открыта'));
  await page.locator('[data-action=work-preview]').click();
  const frame=page.locator('#qw-print-preview-frame').contentFrame();
  await frame.locator('.qw-print-page .qw-callout mfrac').waitFor();
  assert.equal(await frame.locator('.qw-print-page .qw-callout').count(),1);
  assert.equal(await frame.locator('.qw-print-page .qw-paper-task>header').first().isVisible(),false);
  await page.locator('#qw-dialog [data-publish-fit=page]').click();
  await shot('formatted-a4');
  await page.locator('#qw-dialog [data-qw-close]').click();
  await page.evaluate(()=>route('bank'));
  await command('bank-new').click();
  await page.locator('[data-bank-source]').click();
  await source().fill(markup);
  await page.locator('[data-bank-source]').click();
  const bankEdit=page.locator('.qw-bank-edit-dialog');
  await bankEdit.locator('.qw-callout').waitFor();
  await bankEdit.locator('[data-editor-scope]').selectOption('document');
  await bankEdit.locator('[data-editor-style=font]').selectOption('serif');
  await shot('bank-formatted-editor');
  await command('bank-edit-save').click();
  const row=page.locator('[data-bank-view]').first();
  await row.waitFor();
  assert.match(await row.textContent(),/Свободные/);
  assert.doesNotMatch(await row.textContent(),/::format|\[\[style|\[\!/);
  const id=await row.getAttribute('data-bank-view');
  assert.equal(await page.evaluate(id=>qwBankRepository.getTask(id).then(record=>record.task.prompt),id),markup);
  await row.click();
  await page.locator('.qw-bank-video-canvas .qw-callout').waitFor();
  await shot('bank-card');
  const {pack,stored}=await page.evaluate(async()=>({
   pack:await qwBankRepository.exportBank(),stored:await qwBankRepository.createVerifiedBackup()
  }));
  const isolated=await browser.newContext({offline:true}),restored=await isolated.newPage();
  await restored.goto(app);
  const imported=await restored.evaluate(async ({pack,stored,id})=>{
   const repository=await qwBankOpen(),initial=await repository.importBank(pack),repeat=await repository.importBank(pack);
   const exchanged=await repository.getTask(id);
   const preview=await repository.inspectRestore(stored);
   await repository.restoreVerifiedBackup({token:preview.token,mode:'replace'});
   return {initial,repeat,exchanged,restored:await repository.getTask(id)};
  },{pack,stored,id});
  assert.deepEqual([imported.initial.imported,imported.repeat.skipped],[1,1]);
  assert.deepEqual(imported.exchanged.task,imported.restored.task);
  assert.equal(imported.restored.task.prompt,markup);
  assert.equal(imported.restored.task.publishing.text.font,'serif');
  await isolated.close();
  assert.deepEqual(errors,[]);
  console.log('PASS visual rich text, context toolbar, formatting and callout edit, formula, undo, roundtrip, A4, bank and backup');
 }finally{await browser.close();}
}
main().catch(error=>{console.error(error);process.exitCode=1;});
