/* TASK145: mathematical graph construction, precise geometry and PDF/QWORK regression. */
const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH||'playwright');
const assert=require('node:assert/strict'),path=require('node:path'),fs=require('node:fs');
const {pathToFileURL}=require('node:url');
(async()=>{
 const root=path.resolve(__dirname,'..'),out=path.join(root,'evidence/task145');
 fs.mkdirSync(out,{recursive:true});
 const browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:900},acceptDownloads:true});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>d.accept());
  await page.goto(pathToFileURL(path.join(root,'Quantum-Office.html')).href);
  await page.evaluate(()=>route('writer'));
  await page.locator('[data-editor="writer"][data-tab="work"]').click();
  const action=k=>page.locator('[data-qw-action="'+k+'"]');
  const add=async(type,prompt)=>{
   await page.locator('#qw-add-type').selectOption(type);
   await page.locator('.qw-left [data-qw-action="add"]').click();
   await page.locator('#qw-prompt').fill(prompt);
  };
  await add('diagram','В треугольнике ABC найдите длину стороны AB и обозначьте высоту.');
  await action('diagram').click();
  const stage=page.locator('#qw-visual-stage svg'),box=await stage.boundingBox();
  await page.locator('[data-tool="triangle"]').click();
  await page.mouse.move(box.x+box.width*.22,box.y+box.height*.2);
  await page.mouse.down();await page.mouse.move(box.x+box.width*.78,box.y+box.height*.8,{steps:7});await page.mouse.up();
  assert.equal(await page.locator('#qw-visual-stage polygon').count(),1);
  assert.equal(await page.locator('[data-vertex-field="label"]').count(),3);
  await page.locator('[data-vertex-index="1"][data-vertex-field="label"]').fill('D');
  await page.locator('[data-vertex-index="1"][data-vertex-field="label"]').dispatchEvent('change');
  await page.locator('[data-edge-index="0"]').fill('6 см');
  await page.locator('[data-edge-index="0"]').dispatchEvent('change');
  assert.match(await page.locator('#qw-visual-stage svg').textContent(),/6 см/);
  const beforeVertex=await page.locator('[data-vertex-index="2"][data-vertex-field="x"]').inputValue();
  const handle=await page.locator('#qw-visual-stage [data-qw-vertex="2"]').boundingBox();
  await page.mouse.move(handle.x+handle.width/2,handle.y+handle.height/2);
  await page.mouse.down();await page.mouse.move(handle.x+handle.width/2+43,handle.y+handle.height/2-21,{steps:5});await page.mouse.up();
  const afterVertex=await page.locator('[data-vertex-index="2"][data-vertex-field="x"]').inputValue();
  assert.notEqual(afterVertex,beforeVertex,'A vertex must move independently of the figure');
  const coords=await page.evaluate(()=>[...document.querySelectorAll('#qw-visual-stage polygon')].map(x=>x.getAttribute('points')));
  assert.ok(coords.length>0);
  await page.locator('#qw-snap-geometry').uncheck();
  assert.equal(await page.locator('#qw-visual-stage [id="qw-geometry-guide"]').count(),0);
  await page.locator('#qw-snap-geometry').check();
  assert.equal(await page.locator('#qw-visual-stage [id="qw-geometry-guide"]').count(),1);
  await page.screenshot({path:path.join(out,'geometry_editor.png')});
  await action('visual-apply').click();
  assert.equal(await page.evaluate(()=>qwCurrent().diagram[0].vertices.length),3);
  assert.equal(await page.evaluate(()=>qwCurrent().diagram[0].edgeLabels[0]),'6 см');
  await add('graph','По графику функции найдите значение в точке x = 2.');
  await action('graph').click();
  await page.locator('#qw-graph-preset').selectOption('parabola');
  assert.equal(await page.evaluate(()=>document.querySelector('#qw-visual-stage svg path[stroke="#186ba3"]')!==null),true);
  assert.equal(await page.locator('[data-curve-param="a"]').count(),1);
  await page.locator('[data-curve-param="a"]').fill('0.5');await page.locator('[data-curve-param="a"]').dispatchEvent('change');
  await page.locator('#qw-graph-preset').selectOption('sin');
  assert.equal(await page.evaluate(()=>document.querySelector('#qw-curve-family').value),'trigonometric');
  assert.equal(await page.evaluate(()=>document.querySelector('#qw-curve-trig').value),'sin');
  await page.locator('#qw-graph-preset').selectOption('v');
  const b=await page.locator('#qw-visual-stage svg').boundingBox();
  await page.mouse.click(b.x+b.width*.57,b.y+b.height*.56);
  const end=await page.evaluate(()=>{const g=document.querySelector('#qw-visual-stage [data-qw-point="4"]');return g!==null;});
  assert.equal(end,true);
  const snapped=await page.evaluate(()=>{const row=document.querySelector('[data-point-row="4"]');return [+row.querySelector('[data-point-field="x"]').value,+row.querySelector('[data-point-field="y"]').value]});
  assert.ok(snapped.every(Number.isInteger),'Graph pointer should snap to integer grid intersections');
  await page.screenshot({path:path.join(out,'function_graph.png')});
  await action('visual-apply').click();
  const saved=page.waitForEvent('download');await action('save').click();const qwork=await saved;
  await qwork.saveAs(path.join(out,'example.qwork'));
  assert.ok(fs.statSync(path.join(out,'example.qwork')).size>200);
  const pdfDownload=page.waitForEvent('download');
  await page.locator('[data-action="work-pdf-student"]').click();const pdf=await pdfDownload;
  const pdfPath=path.join(out,'example.pdf');await pdf.saveAs(pdfPath);
  assert.equal(fs.readFileSync(pdfPath).subarray(0,5).toString(),'%PDF-');
  assert.deepEqual(errors,[]);
  console.log('PASS TASK145 browser: labeled geometry, construction grid, function curves, snapping, QWORK and PDF');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
