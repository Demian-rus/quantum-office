
const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH||'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const {pathToFileURL}=require('node:url');
(async()=>{
  const root=path.resolve(__dirname,'..'),browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
  const page=await browser.newPage({viewport:{width:1370,height:920},acceptDownloads:true});
  const errors=[];page.on('pageerror',err=>errors.push(err.message));page.on('dialog',d=>d.accept());
  await page.goto(pathToFileURL(path.join(root,'Quantum-Office.html')).href);
  await page.evaluate(()=>route('writer'));
  await page.locator('[data-editor="writer"][data-tab="diagnostic"]').click();
  assert.equal(await page.locator('#qo-diag-workspace').isVisible(),true);
  assert.equal(await page.locator('#qo-writer-edit-scroll').isVisible(),false);
  await page.locator('[data-qd-action="sample"]').click();
  assert.equal(await page.locator('.qd-edit-card').count(),8);
  await page.locator('[data-qd-action="mode"][data-mode="run"]').first().click();
  assert.equal(await page.locator('.qd-card[data-qid]').count(),8);
  await page.locator('[data-qd-action="reveal"]').first().click();
  assert.equal(await page.locator('.qd-answer').count(),1);
  const buttons=page.locator('[data-qd-action="mark"]');
  await buttons.filter({hasText:'Знает'}).first().click();
  await page.locator('[data-qd-action="mark"][data-mark="partial"]').nth(1).click();
  assert.match(await page.locator('.qd-percent').textContent(),/75%/);
  assert.match(await page.locator('.qd-metrics').textContent(),/2 \/ 8/);
  await page.reload();await page.evaluate(()=>route('writer'));
  await page.locator('[data-editor="writer"][data-tab="diagnostic"]').click();
  assert.match(await page.locator('.qd-percent').textContent(),/75%/);
  await page.locator('[data-qd-field="student"]').fill('Ученик 1');
  await page.locator('[data-qd-action="save-result"]').click();
  assert.match(await page.locator('.qd-history').textContent(),/Ученик 1/);
  assert.match(await page.locator('.qd-metrics').textContent(),/0 \/ 8/);
  const pending=page.waitForEvent('download');
  await page.locator('[data-qd-action="export"]').click();
  const downloaded=await pending;assert.match(downloaded.suggestedFilename(),/\.qdiag$/);
  const output=path.join(root,'task099-diagnostic-test.qdiag');await downloaded.saveAs(output);
  const saved=JSON.parse(fs.readFileSync(output,'utf8'));assert.equal(saved.sections.length,3);
  assert.equal(saved.history.length,1);
  await page.locator('[data-qd-action="mode"][data-mode="builder"]').first().click();
  await page.locator('[data-qd-field="title"]').fill('Моя проверка');
  await page.locator('#qo-diag-file').setInputFiles(output);
  assert.match(await page.locator('#qo-diag-root h1').textContent(),/Физика/);
  await page.locator('[data-editor="writer"][data-tab="home"]').click();
  assert.equal(await page.locator('#qo-writer-edit-scroll').isVisible(),true);
  await page.locator('#qo-writer-page').fill('Текст сохранён отдельно от диагностики');
  const p=page.waitForEvent('download');
  await page.evaluate(()=>qoWriterExport('qdoc'));
  const qdoc=await p;
  const qdocPath=path.join(root,'task099-writer-test.qdoc');await qdoc.saveAs(qdocPath);
  const content=JSON.parse(fs.readFileSync(qdocPath,'utf8'));
  assert.match(content.html,/Текст сохранён/);
  assert.equal(content.diagnostic.history.length,1);
  fs.rmSync(output,{force:true});fs.rmSync(qdocPath,{force:true});
  assert.deepEqual(errors,[]);
  console.log('PASS TASK099: builder, 8 cards, answers, weighted results, reload, history, import, QDOC');
  await browser.close();
})().catch(e=>{console.error(e.stack);process.exit(1);});
