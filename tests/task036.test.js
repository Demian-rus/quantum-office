import test from 'node:test';
import assert from 'node:assert/strict';
import {newWorkbook,currentSheet,setCell,setStyle,getCell,getEffectiveStyle,setBulkColumnStyle,setWholeSheetAlignment,clearFormatting,displayedValue,rawMap,formulaContext,validateWorkbook,LIMITS} from '../src/core/workbook.js';
import {encodeBook,decodeBook} from '../src/core/store.js';
import {copyCells,pasteCells} from '../src/core/clipboard.js';
import {exportXLSX} from '../src/core/xlsx.js';

test('full sheet fill/colors and whole-column styles take constant storage, including row 100000',()=>{
 const b=newWorkbook(),s=currentSheet(b);
 setCell(s,'B3','Текст');setStyle(s,'B3',{bg:'#ff0000',bold:true});
 setCell(s,'CV100000','Конец');
 setBulkColumnStyle(s,'A1','CV100000',{bg:'#facc15'});
 assert.equal(Object.keys(s.cells).length,2);
 assert.deepEqual(s.defaultStyle,{bg:'#facc15'});
 assert.equal(getEffectiveStyle(s,'Z99999').bg,'#facc15');
 assert.equal(getEffectiveStyle(s,'B3').bg,'#facc15');
 assert.equal(getEffectiveStyle(s,'B3').bold,true);
 setBulkColumnStyle(s,'B1','C100000',{bg:'#93c5fd'});
 assert.equal(Object.keys(s.columnStyles).length,2);
 assert.equal(getEffectiveStyle(s,'B99999').bg,'#93c5fd');
 assert.equal(getEffectiveStyle(s,'D99999').bg,'#facc15');
 assert.equal(getEffectiveStyle(s,'CV100000').bg,'#facc15');
 assert.equal(getCell(s,'B3').value,'Текст');
 assert.equal(Object.keys(s.cells).length,2);
 validateWorkbook(b);
});
test('whole-column formats preserve individual properties, later per-cell override, native persistence',()=>{
 const b=newWorkbook(),s=currentSheet(b);
 setCell(s,'B50000','123');setStyle(s,'B50000',{bold:true,borders:{top:true}});
 setBulkColumnStyle(s,'B1','B100000',{format:'currency'});
 assert.equal(getEffectiveStyle(s,'B50000').format,'currency');
 assert.match(displayedValue(s,'B50000',rawMap(s),formulaContext(b,s)),/123/);
 setStyle(s,'B50000',{color:'#ff0000'});
 assert.equal(getEffectiveStyle(s,'B50000').color,'#ff0000');
 setBulkColumnStyle(s,'A1','CV100000',{color:'#17365d'});
 assert.equal(getEffectiveStyle(s,'B50000').color,'#17365d');
 assert.deepEqual(getCell(s,'B50000').style.borders,{top:true});
 const rt=decodeBook(encodeBook(b));
 assert.deepEqual(rt.sheets[0].defaultStyle,s.defaultStyle);
 assert.deepEqual(rt.sheets[0].columnStyles,s.columnStyles);
 assert.equal(getEffectiveStyle(rt.sheets[0],'B99999').format,'currency');
});
test('whole sheet center overrides previous column alignment; later override remains local',()=>{
 const s=currentSheet(newWorkbook());
 setBulkColumnStyle(s,'B1','C100000',{align:'right'});
 assert.equal(getEffectiveStyle(s,'B70000').align,'right');
 setWholeSheetAlignment(s,'center');
 assert.equal(getEffectiveStyle(s,'B70000').align,'center');
 setBulkColumnStyle(s,'C1','C100000',{align:'left'});
 assert.equal(getEffectiveStyle(s,'C70000').align,'left');
 assert.equal(getEffectiveStyle(s,'B70000').align,'center');
});
test('full column and full-sheet formatting resets only intended scope, no cell expansion',()=>{
 const b=newWorkbook(),s=currentSheet(b);
 setCell(s,'B10','Сохранить');setStyle(s,'B10',{bold:true});
 setBulkColumnStyle(s,'A1','CV100000',{bg:'#abcdef'});
 setBulkColumnStyle(s,'B1','B100000',{color:'#090909'});
 assert.equal(clearFormatting(s,'B1','B100000'),2);
 assert.equal(s.defaultStyle.bg,'#abcdef');
 assert.equal(getEffectiveStyle(s,'B10').color,undefined);
 assert.equal(getEffectiveStyle(s,'B10').bg,'#abcdef');
 assert.equal(getCell(s,'B10').value,'Сохранить');
 assert.equal(clearFormatting(s,'A1','CV100000'),1);
 assert.deepEqual(s.defaultStyle,{});
 assert.deepEqual(s.columnStyles,{});
 assert.equal(getCell(s,'B10').value,'Сохранить');
 validateWorkbook(b);
});
test('clipboard uses inherited column fill, format and font, even for empty virtual cells',()=>{
 const s=currentSheet(newWorkbook());
 setBulkColumnStyle(s,'B1','B100000',{bg:'#abcdef'});
 setBulkColumnStyle(s,'B1','B100000',{bold:true});
 const clip=copyCells(s,'B50000','B50000');
 assert.equal(clip.cells[0][0].style.bg,'#abcdef');
 assert.equal(clip.cells[0][0].style.bold,true);
 pasteCells(s,'D20',clip);
 assert.equal(getCell(s,'D20').style.bg,'#abcdef');
 assert.equal(getCell(s,'D20').style.bold,true);
});
test('XLSX stores one column style across 100k rows without materializing 100k cells',async()=>{
 const b=newWorkbook(),s=currentSheet(b);
 setCell(s,'B100000','Низ');
 setStyle(s,'B1',{color:'#fb923c'}); // This isolated cell must not color entire column.
 setBulkColumnStyle(s,'B1','B100000',{bg:'#aabbcc'});
 setBulkColumnStyle(s,'B1','B100000',{align:'center'});
 const zip=await globalThis.JSZip.loadAsync(await exportXLSX(b),{checkCRC32:true});
 const xml=await zip.file('xl/worksheets/sheet1.xml').async('string');
 const styles=await zip.file('xl/styles.xml').async('string');
 assert.match(xml,/<col min="2" max="2"[^>]*style="\d+"/);
 assert.match(xml,/r="B100000"/);
 assert.equal((xml.match(/<c /g)||[]).length,2);
 const columnId=/<col min="2" max="2"[^>]*style="(\d+)"/.exec(xml)?.[1];
 const firstCellId=/<c r="B1"[^>]*s="(\d+)"/.exec(xml)?.[1];
 assert.ok(columnId&&firstCellId);
 assert.notEqual(columnId,firstCellId,'B1 custom color leaked to whole column');
 assert.match(styles,/FFAABBCC/);
 assert.match(styles,/horizontal="center"/);
});
test('invalid sparse formats are rejected, including oversized or malformed columnStyle indices',()=>{
 const b=newWorkbook(),s=currentSheet(b);
 assert.throws(()=>setBulkColumnStyle(s,'B2','C100000',{bg:'#123456'}),/целые столбцы/);
 assert.throws(()=>setBulkColumnStyle(s,'B1','B100000',{bg:'red'}),/цвет/);
 assert.throws(()=>setBulkColumnStyle(s,'B1','B100000',{borders:{top:true}}),/массовое оформление/);
 s.columnStyles={'100':{bg:'#abcdef'}};
 assert.throws(()=>validateWorkbook(b),/оформление столбцов/);
 s.columnStyles={'1':{bg:'not-a-color'}};
 assert.throws(()=>validateWorkbook(b),/оформление столбцов/);
 s.columnStyles={};s.defaultStyle={italic:'true'};
 assert.throws(()=>validateWorkbook(b),/оформление листа/);
});
