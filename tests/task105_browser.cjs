const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH||'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const {pathToFileURL}=require('node:url');

(async()=>{
 const root=path.resolve(__dirname,'..'),browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
 const page=await browser.newPage({viewport:{width:1310,height:900},acceptDownloads:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>d.accept());
 await page.goto(pathToFileURL(path.join(root,'Quantum-Office.html')).href);
 const open=async()=>{await page.evaluate(()=>route('writer'));await page.locator('[data-editor="writer"][data-tab="diagnostic"]').click();};
 await open();await page.locator('[data-qd-action="sample"]').click();
 assert.equal(await page.locator('.qd-edit-card:visible').count(),8);
 await page.locator('#qd-search').fill('сахар');
 assert.equal(await page.locator('.qd-edit-card:visible').count(),1);
 await page.locator('#qd-search').fill('');
 await page.locator('#qd-filter-kind').selectOption('practice');
 assert.equal(await page.locator('.qd-edit-card:visible').count(),2);
 await page.locator('[data-qd-action="select-visible"]').click();
 assert.equal(await page.locator('.qd-select-card:checked').count(),2);
 assert.match(await page.locator('#qd-selection-count').textContent(),/2 выбрано/);
 await page.locator('#qd-batch-value').fill('5');
 await page.locator('[data-qd-action="batch-apply"]').click();
 assert.equal(await page.evaluate(()=>qdQuestionList().filter(q=>q.type==='practice'&&q.points===5).length),2);
 await page.locator('[data-qd-action="select-visible"]').click();
 await page.locator('#qd-batch-action').selectOption('move');
 const firstSection=await page.evaluate(()=>qdDoc().sections[0].id);
 await page.locator('#qd-batch-value').selectOption(firstSection);
 await page.locator('[data-qd-action="batch-apply"]').click();
 assert.equal(await page.evaluate(()=>qdDoc().sections[0].questions.filter(q=>q.type==='practice').length),2);
 assert.equal(await page.locator('.qd-edit-card:visible').count(),2);
 await page.locator('[data-qd-action="select-visible"]').click();
 await page.locator('#qd-batch-action').selectOption('type');
 await page.locator('#qd-batch-value').selectOption('question');
 await page.locator('[data-qd-action="batch-apply"]').click();
 assert.equal(await page.locator('.qd-edit-card:visible').count(),0);
 assert.equal(await page.locator('#qd-no-matches:visible').count(),1);
 await page.locator('#qd-filter-kind').selectOption('all');
 assert.equal(await page.locator('.qd-edit-card:visible').count(),8);
 await page.locator('#qd-search').fill('Сколько теплоты');
 assert.equal(await page.locator('.qd-edit-card:visible').count(),1);
 await page.locator('[data-qd-action="select-visible"]').click();
 await page.locator('#qd-batch-action').selectOption('delete');
 await page.locator('[data-qd-action="batch-apply"]').click();
 assert.equal(await page.evaluate(()=>qdQuestionList().length),7);
 await page.reload();await open();
 assert.equal(await page.evaluate(()=>qdQuestionList().length),7);
 assert.equal(await page.locator('.qd-edit-card:visible').count(),7);
 const pending=page.waitForEvent('download');await page.locator('[data-qd-action="export"]').click();
 const dl=await pending,dest=path.join(root,'task105-test.qdiag');await dl.saveAs(dest);
 const data=JSON.parse(fs.readFileSync(dest,'utf8'));
 assert.equal(data.sections.flatMap(s=>s.questions).length,7);
 assert.equal(data.sections[0].questions.filter(q=>q.points===5).length,2);
 fs.rmSync(dest,{force:true});
 assert.deepEqual(errors,[]);
 console.log('PASS TASK105: live filtering, select visible, batch points/move/type/delete, reload and QDIAG');
 await browser.close();
})().catch(e=>{console.error(e.stack);process.exit(1);});