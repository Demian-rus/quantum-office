/* TASK163: real QWBANK catalogue and video preview, no second storage schema. */
const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH||'playwright');
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),{pathToFileURL}=require('node:url');
const root=path.resolve(__dirname,'..'),out=path.join(root,'evidence/task163-bank');
(async()=>{
 fs.mkdirSync(out,{recursive:true});
 const browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
 try{
  const p=await browser.newPage({viewport:{width:1600,height:1000}});
  const errors=[];p.on('pageerror',e=>errors.push(e.message));
  await p.goto(pathToFileURL(path.join(root,'Quantum-Office.html')).href);
  await p.evaluate(()=>{
   const t=qwTask('graph');t.prompt='По графику скорости определите путь за 6 секунд.';
   t.answer='18 м';t.comment='Путь равен площади под графиком скорости. За 6 секунд получается 18 м.';
   t.figure='graph';t.position='right';t.graph.points=[{x:0,y:0,label:''},{x:6,y:6,label:''}];
   const x=qwBankNormalize({id:'bank-kinematics',bankNumber:1801,subject:'physics',exam:'ege',grade:'11',year:'2018',slot:'7',topic:'Механика',subtopic:'Кинематика',difficulty:'basic',origin:'adapted',task:t});
   const a=qwTask('short');a.prompt='Определите сопротивление резистора.';a.answer='6 Ом';a.comment='Используйте закон Ома.';
   const y=qwBankNormalize({id:'bank-electric',bankNumber:1802,subject:'physics',exam:'ege',grade:'11',year:'2019',slot:'6',topic:'Электричество',subtopic:'Закон Ома',origin:'original',task:a});
   localStorage.setItem(QW_BANK_KEY,JSON.stringify([x,y]));
   localStorage.setItem(QW_BANK_NUMBER_KEY,'1802');
  });
  await p.locator('[data-action="launcher-bank"]').click();
  const dialog=p.locator('#qw-dialog');
  await p.waitForFunction(()=>document.querySelectorAll('#qw-bank-list [data-bank-entry]').length===2);
  assert.equal(await dialog.locator('#qw-bank-list [data-bank-entry]').count(),2);
  assert.equal(await dialog.locator('.qw-bank-catalogue-preview').count(),1);
  await dialog.locator('.qw-bank-video-canvas svg').waitFor({state:'visible'});
  assert.equal(await dialog.locator('.qw-bank-video-canvas svg').count()>0,true,'vector graph must be visible');
  assert.equal(await dialog.locator('.qw-bank-solution').evaluate(e=>e.open),false,'solution collapsed by default');
  await dialog.locator('.qw-bank-solution summary').click();
  assert.match(await dialog.locator('.qw-bank-solution-body').innerText(),/18 м/);
  assert.match(await dialog.locator('.qw-bank-solution-body').innerText(),/площади под графиком/);
  assert.equal(await dialog.locator('.qw-bank-extra-filters').evaluate(e=>e.open),false,'advanced filters initially collapsed');
  await dialog.locator('.qw-bank-extra-filters summary').click();
  await dialog.locator('#qw-bank-year').selectOption('2019');
  await p.waitForFunction(()=>document.querySelectorAll('#qw-bank-list [data-bank-entry]').length===1);
  assert.equal(await dialog.locator('#qw-bank-list [data-bank-entry]').count(),1,'advanced year filter');
  await dialog.locator('#qw-bank-year').selectOption('all');
  await p.waitForFunction(()=>document.querySelectorAll('#qw-bank-list [data-bank-entry]').length===2);
  await dialog.locator('.qw-bank-extra-filters summary').click();
  await dialog.locator('#qw-bank-topic').selectOption('Электричество');
  await p.waitForFunction(()=>document.querySelectorAll('#qw-bank-list [data-bank-entry]').length===1);
  assert.equal(await dialog.locator('#qw-bank-list [data-bank-entry]').count(),1,'topic filter');
  await dialog.locator('#qw-bank-topic').selectOption('all');
  await p.waitForFunction(()=>document.querySelectorAll('#qw-bank-list [data-bank-entry]').length===2);
  await dialog.locator('#qw-bank-search').fill('Кинематика');
  await p.waitForFunction(()=>document.querySelectorAll('#qw-bank-list [data-bank-entry]').length===1);
  assert.equal(await dialog.locator('#qw-bank-list [data-bank-entry]').count(),1,'search by subtopic');
  await dialog.locator('#qw-bank-search').fill('');
  await dialog.locator('[data-bank-view="bank-kinematics"]').click();
  await dialog.locator('[data-bank-enlarge]').click();
  assert.equal(await dialog.evaluate(el=>el.classList.contains('qw-bank-expanded')),true);
  assert.equal(await dialog.locator('.qw-bank-video-canvas').isVisible(),true);
  assert.equal(await dialog.locator('.qw-bank-solution').isVisible(),true,'solution remains available in enlarged view');
  await p.screenshot({path:path.join(out,'large-preview.png'),fullPage:true});
  await dialog.locator('[data-bank-enlarge]').click();
  assert.equal(await dialog.evaluate(el=>el.classList.contains('qw-bank-expanded')),false);
  await dialog.locator('.qw-bank-preview-actions [data-bank-edit]').click();
  await p.locator('[data-bank-source]').click();
  const editor=p.locator('#qw-dialog');
  await editor.locator('[data-bank-task-field="prompt"]').fill('Изменённая задача о движении.');
  await editor.locator('[data-qw-action="bank-edit-save"]').click();
  await p.waitForFunction(()=>qwBankRead().find(x=>x.id==='bank-kinematics')?.task.prompt==='Изменённая задача о движении.');
  await p.locator('#qw-dialog [data-qw-action="bank-new"]').click();
  await p.locator('[data-bank-source]').click();
  await p.locator('#qw-dialog [data-bank-task-field="prompt"]').fill('Авторский аналог о тепловом равновесии.');
  await editor.locator('[data-bank-tab="answer"]').click();
  await p.locator('#qw-dialog [data-bank-task-field="answer"]').fill('24 °C');
  await editor.locator('[data-bank-tab="comment"]').click();
  await p.locator('#qw-dialog [data-bank-task-field="comment"]').fill('Составить уравнение теплового баланса.');
  await p.locator('#qw-dialog [data-bank-edit-field="topic"]').fill('Тепловые явления');
  await p.locator('#qw-dialog [data-qw-action="bank-edit-save"]').click();
  await p.waitForFunction(()=>qwBankRead().length===3);
  const saved=await p.evaluate(()=>qwBankRead().find(x=>x.task.prompt.includes('тепловом')));
  assert.ok(saved&&saved.bankNumber>1802&&saved.topic==='Тепловые явления');
  await p.locator('#qw-dialog [data-qw-action="bank-new"]').click();
  await p.locator('#qw-dialog [data-qw-action="bank-edit-back"]').click();
  assert.equal(await p.evaluate(()=>qwBankRead().length),3,'cancel does not create empty entry');
  await p.locator('#qw-dialog [data-qw-action="bank-new"]').click();
  await p.locator('[data-bank-source]').click();
  await p.locator('#qw-dialog [data-bank-task-field="type"]').selectOption('choice');
  await p.locator('#qw-dialog [data-bank-task-field="prompt"]').fill('Какой величиной измеряется напряжение?');
  await p.locator('#qw-dialog [data-bank-choices]').fill('Вольт\nАмпер\nОм');
  await p.locator('#qw-dialog [data-qw-action="bank-edit-save"]').click();
  await p.waitForFunction(()=>qwBankRead().length===4);
  assert.deepEqual(await p.evaluate(()=>qwBankRead().find(x=>x.task.prompt==='Какой величиной измеряется напряжение?')?.task.choices),['Вольт','Ампер','Ом'],'choice options survive bank validation');
  await p.screenshot({path:path.join(out,'catalogue.png'),fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('PASS TASK163: filter, select, enlarged SVG, collapsed solution, large view, edit/save, new entry and safe cancel');
  await p.close();
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
