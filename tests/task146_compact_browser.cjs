/* TASK146 continuation: compact exam PDF, worksheet layout, icon palette, physics illustration. */
const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH||'playwright');
const assert=require('node:assert/strict');
const {readFileSync,writeFileSync,mkdirSync}=require('node:fs');
const {execFileSync}=require('node:child_process');
const path=require('node:path'),{pathToFileURL}=require('node:url');
(async()=>{
 const root=path.resolve(__dirname,'..'),out=path.join(process.env.QW_REGRESSION_ROOT||path.join(root,'evidence'),'task146/compact');
 mkdirSync(out,{recursive:true});
 const browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
 try{
  const p=await browser.newPage({viewport:{width:1440,height:900},acceptDownloads:true});
  const errors=[];p.on('pageerror',e=>errors.push(e.message));
  await p.goto(pathToFileURL(path.join(root,'Quantum-Office.html')).href);
  await p.evaluate(()=>route('writer'));await p.locator('[data-editor="writer"][data-tab="work"]').click();
  const action=k=>p.locator('[data-qw-action="'+k+'"]');
  await p.locator('[data-qw-action="quick-add"][data-type="'+'diagram'+'"]').click();
  await p.locator('#qw-prompt').fill('Брусок массой m находится на наклонной плоскости. Найдите работу силы тяжести. \\(A=mgh\\).');
  await action('diagram').click();
  const tools=await p.locator('[data-tool]').evaluateAll(xs=>xs.map(x=>({key:x.dataset.tool,text:x.textContent.trim(),title:x.title,aria:x.getAttribute('aria-label')})));
  assert.deepEqual(tools.slice(0,3).map(x=>x.key),['select','point','line']);
  assert.ok(tools.length>=18);
  assert.ok(tools.every(x=>x.text&&x.aria&&x.title));
  assert.equal(await p.locator('.qw-visual-tools [data-tool="incline"] svg').count(),1);
  await p.locator('#qw-diagram-preset').selectOption('incline');
  const incline=await p.locator('#qw-visual-stage [data-qw-object="0"] polygon').getAttribute('points');
  const [base,,top]=incline.split(' ').map(s=>s.split(',').map(Number));
  const slope=Math.atan2(top[1]-base[1],top[0]-base[0])*180/Math.PI;
  const transform=await p.locator('#qw-visual-stage [data-qw-object="1"]').getAttribute('transform');
  assert.ok(Math.abs(Number(transform.match(/rotate\(([-.\d]+)/)[1])-slope)<.001,'preset block must align with the actual inclined surface');
  await p.locator('[data-object-select="1"]').click();
  await p.locator('#qw-block-rotation').fill('-20');await p.locator('#qw-block-rotation').dispatchEvent('change');
  assert.ok(await p.locator('#qw-visual-stage [transform*="rotate(-20"]').count()>0);
  const inputBox=await p.locator('#qw-object-label').boundingBox();
  const modalBox=await p.locator('#qw-dialog').boundingBox();
  assert.ok(inputBox.x>=modalBox.x,'label field must be inside editor dialog');
  assert.ok(inputBox.x+inputBox.width<=modalBox.x+modalBox.width,'label field must not overflow');
  await p.screenshot({path:path.join(out,'physics_editor.png')});
  await action('visual-apply').click();
  assert.equal(await p.evaluate(()=>qwCurrent().diagram.some(x=>x.kind==='block'&&x.rotation===-20)),true);
  // Reopen the legacy layout; it is no longer offered as an official exam template.
  await p.evaluate(()=>qwChange(()=>{qwDoc.layout='exam';qwDoc.exam='ege';}));
  await action('settings').click();
  assert.equal(await p.locator('[data-meta="layout"] option[value="exam"]').textContent(),'Прежний компактный макет (без проверки ФИПИ)');
  await p.locator('[data-meta="title"]').fill('Физика — тренировочный вариант');
  await p.locator('[data-meta="layout"]').selectOption('exam');
  await p.locator('[data-qw-action="meta-apply"]').click();
  const exam=await p.evaluate(()=>qwPrintDocumentHTML(qwDoc,false));
  assert.match(exam,/qw-print-exam/);
  assert.match(exam,/qw-exam-task/);
  assert.match(exam,/<h1 class="qw-print-title">Физика — тренировочный вариант<\/h1>/);
  assert.match(exam,/<div class="qw-print-meta">Физика · 8 класс · Вариант 1<\/div>/);
  assert.match(exam,/<svg/);
  assert.match(exam,/<mo lspace="0.28em" rspace="0.28em">=<\/mo>/);
  assert.doesNotMatch(exam,/Задание 1 · Рисунок/);
  assert.doesNotMatch(exam,/PDF \(растровый\)/);
  assert.equal(await p.locator('[data-action="work-pdf"]').count(),1);
  assert.equal(await p.locator('[data-action^="work-pdf-"]:not([data-action="work-pdf"])').count(),0);
  await action('preview').click();
  await p.frameLocator('#qw-print-preview-frame').locator('.qw-exam-task').first().waitFor();
  assert.equal(await p.locator('[data-qw-action="preview-pdf"]').count(),1);
  await p.screenshot({path:path.join(out,'ege_preview.png')});
  await p.locator('#qw-dialog [data-qw-close]').click();
  const print=await browser.newPage({viewport:{width:1000,height:1300}});
  await print.setContent(exam,{waitUntil:'load'});
  await print.evaluate(()=>window.qwPrintReady);
  const pdf=await print.pdf({preferCSSPageSize:true,printBackground:true,format:'A4'});
  assert.equal(pdf.subarray(0,5).toString(),'%PDF-');
  writeFileSync(path.join(out,'ege_vector.pdf'),pdf);
  const circle=await print.locator('.qw-exam-task figure svg').count();
  assert.equal(circle,1);
  try{
    const txt=execFileSync(process.env.QW_PYTHON||'python',['-c','import pymupdf,sys; sys.stdout.buffer.write(pymupdf.open(sys.argv[1])[0].get_text().encode("utf-8"))',path.join(out,'ege_vector.pdf')],{encoding:'utf8'});
    assert.match(txt,/Брусок массой/);
    assert.match(txt,/Физика — тренировочный вариант/);
    assert.match(txt,/Физика · 8 класс · Вариант 1/);
    assert.match(txt,/^1 \/ 1$/m);
  }catch(err){if(err.code!=='ENOENT')throw err;}
  await print.close();
  await action('settings').click();
  await p.locator('[data-meta="layout"]').selectOption('worksheet');
  await p.locator('[data-qw-action="meta-apply"]').click();
  const worksheet=await p.evaluate(()=>qwPrintDocumentHTML(qwDoc,false));
  assert.match(worksheet,/qw-print-worksheet/);
  assert.match(worksheet,/Задание 1/);
  assert.match(worksheet,/qw-answer-preview/);
  await action('preview').click();
  await p.frameLocator('#qw-print-preview-frame').locator('.qw-worksheet-task').first().waitFor();
  await p.screenshot({path:path.join(out,'worksheet_preview.png')});
  await p.locator('#qw-dialog [data-qw-close]').click();
  assert.deepEqual(errors,[]);
  writeFileSync(path.join(out,'result.json'),JSON.stringify({status:'PASS',tools:tools.length,pdfBytes:pdf.length},null,2));
  console.log('PASS TASK146 compact exam/worksheet preview, selectable PDF, icon tools, physics blocks');
 }finally{await browser.close();}
})().catch(e=>{console.error(e.stack||e);process.exitCode=1;});
