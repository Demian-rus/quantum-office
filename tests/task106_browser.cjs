const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH||'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const {pathToFileURL}=require('node:url');
(async()=>{
 const root=path.resolve(__dirname,'..');
 const browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
 const page=await browser.newPage({viewport:{width:1600,height:950},acceptDownloads:true});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));page.on('dialog',d=>d.accept());
 await page.goto(pathToFileURL(path.join(root,'Quantum-Office.html')).href);
 await page.evaluate(()=>route('writer'));
 await page.locator('[data-editor="writer"][data-tab="diagnostic"]').click();
 assert.ok(await page.locator('.qo-document-workspace [data-editor-panel="writer"][data-panel-tab="diagnostic"] .qo-work-group').count()>=3);
 await page.locator('[data-qd-action="mode"][data-mode="library"]').click();
 assert.equal(await page.locator('.qd-library-card').count(),7);
 const width=await page.evaluate(()=>({
   root:document.querySelector('#qo-diag-root').getBoundingClientRect().width,
   screen:document.querySelector('#qo-diag-workspace').getBoundingClientRect().width,
   ribbon:document.querySelector('.qo-work-ribbon').getBoundingClientRect().width}));
 console.log('TASK106 layout widths',JSON.stringify(width));
 assert.ok(width.root>1100,'diagnostics must use large desktop width, not old 900px column');
 await page.locator('#qd-library-subject').selectOption('physics');
 await page.locator('#qd-library-grade').selectOption('8');
 assert.equal(await page.locator('.qd-library-card').count(),1);
 assert.match(await page.locator('.qd-library-card h3').textContent(),/Молекулы и температура/);
 await page.locator('[data-qd-action="library-open"]').click();
 assert.equal(await page.locator('.qd-chat-card').count(),10);
 assert.equal(await page.locator('[data-qd-action="view"][data-view="list"]').getAttribute('aria-pressed'),'true');
 const positions=await page.locator('.qd-chat-card').first().evaluate(el=>{
   const q=el.querySelector('.qd-question').getBoundingClientRect();
   const rating=el.querySelector('.qd-chat-rating').getBoundingClientRect();
   const outer=el.getBoundingClientRect();
   return {questionX:q.x,questionWidth:q.width,ratingX:rating.x,right:outer.right};
 });
 assert.ok(positions.ratingX>=positions.questionX+positions.questionWidth-2,'grade buttons must appear right of question');
 await page.locator('.qd-chat-card [data-qd-action="reveal"]').first().click();
 assert.equal(await page.locator('.qd-chat-card .qd-chat-answer').count(),1);
 assert.match(await page.locator('.qd-chat-card .qd-chat-answer').first().textContent(),/частиц/);
 await page.locator('.qd-chat-card [data-qd-action="mark"][data-mark="yes"]').first().click();
 assert.equal(await page.evaluate(()=>Object.values(qdDoc().session.marks).filter(x=>x==='yes').length),1);
 await page.locator('[data-qd-action="view"][data-view="focus"]').click();
 assert.equal(await page.locator('.qd-guided .qd-chat-card').count(),1);
 await page.locator('[data-qd-action="view"][data-view="list"]').click();
 assert.equal(await page.locator('.qd-chat-card').count(),10);
 await page.locator('[data-qd-action="mode"][data-mode="library"]').click();
 await page.locator('#qd-library-save-subject').selectOption('physics');
 await page.locator('#qd-library-save-grade').fill('8');
 await page.locator('[data-qd-action="library-save"]').click();
 assert.equal(await page.locator('.qd-library-card').count(),2,'custom template must show next to matching built-in');
 const pending=page.waitForEvent('download');
 await page.locator('[data-action="writer-diag-templates-export"]').click();
 const dl=await pending;
 assert.match(dl.suggestedFilename(),/\.qtpl$/);
 const file=path.join(root,'task106-smoke.qtpl');await dl.saveAs(file);
 const saved=JSON.parse(fs.readFileSync(file,'utf8'));
 assert.equal(saved.templates.length,1);
 assert.ok(!JSON.stringify(saved).includes('"history"'));
 assert.ok(!JSON.stringify(saved).includes('"student"'));
 await page.reload();
 await page.evaluate(()=>route('writer'));
 await page.locator('[data-editor="writer"][data-tab="diagnostic"]').click();
 await page.locator('[data-qd-action="mode"][data-mode="library"]').click();
 await page.locator('#qd-library-subject').selectOption('physics');
 await page.locator('#qd-library-grade').selectOption('8');
 assert.equal(await page.locator('.qd-library-card').count(),2,'custom template should persist across reload of same HTML');
 await page.locator('[data-qd-action="library-delete"]').click();
 assert.equal(await page.locator('.qd-library-card').count(),1);
 await page.locator('[data-action="writer-diag-templates-import"]').click();
 await page.locator('#qd-library-file').setInputFiles(file);
 await page.locator('.qd-library-card').nth(1).waitFor({state:'visible',timeout:5000});
 assert.equal(await page.locator('.qd-library-card').count(),2,'portable template must restore after import');
 fs.rmSync(file,{force:true});
 assert.deepEqual(errors,[]);
 console.log('PASS TASK106: full-width workspace, real ribbon, library filtering, screenshot-style grading and portable presets');
 await browser.close();
})().catch(error=>{console.error(error.stack);process.exit(1);});