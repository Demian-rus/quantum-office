const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH||'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const {pathToFileURL}=require('node:url');
(async()=>{
 const root=path.resolve(__dirname,'..'),browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
 const page=await browser.newPage({viewport:{width:1300,height:920},acceptDownloads:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>d.accept());
 await page.goto(pathToFileURL(path.join(root,'Quantum-Office.html')).href);
 const open=async()=>{await page.evaluate(()=>route('writer'));await page.locator('[data-editor="writer"][data-tab="diagnostic"]').click();};
 await open();
 await page.locator('[data-qd-pane="bulk"] summary').click();
 const text=['[Энергия]','Почему тела нагреваются? | Из-за передачи энергии',
  '! Вычисли 2 + 2 | 4','Почему тела нагреваются? | Повтор'].join('\n');
 await page.locator('#qd-bulk-text').fill(text);
 assert.match(await page.locator('#qd-bulk-preview').textContent(),/Добавится 2 заданий/);
 assert.match(await page.locator('#qd-bulk-preview').textContent(),/Пропущено: 1/);
 await page.locator('[data-qd-action="bulk-commit"]').click();
 assert.equal(await page.locator('.qd-edit-card').count(),3);
 assert.equal(await page.evaluate(()=>qdDoc().sections.length),2);
 assert.equal(await page.evaluate(()=>qdQuestionList().filter(q=>q.type==='practice').length),1);
 assert.equal(await page.locator('[data-qd-pane="audit"]').getAttribute('open'),'');
 await page.locator('[data-qd-action="audit-jump"]').first().click();
 assert.equal(await page.evaluate(()=>document.activeElement?.dataset?.qdField),'prompt');
 await page.locator('[data-qd-action="compact-mode"]').click();
 assert.equal(await page.locator('.qd-edit-card.is-compact').count(),3);
 await page.locator('[data-qd-action="card-expand"]').first().click();
 assert.equal(await page.locator('.qd-edit-card.is-compact').count(),2);
 assert.equal(await page.locator('.qd-edit-card:not(.is-compact) [data-qd-field="prompt"]').count(),1);
 await page.locator('.qd-edit-card:not(.is-compact) [data-qd-field="prompt"]').fill('Проверочный вопрос для ученика');
 await page.locator('[data-qd-action="compact-mode"]').click();
 assert.equal(await page.locator('.qd-edit-card.is-compact').count(),0);
 await page.locator('[data-qd-pane="audit"] summary').click();
 await page.locator('[data-qd-pane="audit"] summary').click();
 await page.reload();await open();
 assert.equal(await page.locator('.qd-edit-card').count(),3);
 assert.equal(await page.evaluate(()=>qdDoc().sections[0].questions[0].prompt),'Проверочный вопрос для ученика');
 assert.equal(await page.evaluate(()=>qdDoc().sections[1].questions[1].answer),'4');
 const pending=page.waitForEvent('download');
 await page.locator('[data-qd-action="export"]').click();
 const dl=await pending,out=path.join(root,'task104-smoke.qdiag');await dl.saveAs(out);
 const d=JSON.parse(fs.readFileSync(out,'utf8'));
 assert.equal(d.sections.length,2);assert.equal(d.sections[1].questions.length,2);
 fs.rmSync(out,{force:true});
 assert.deepEqual(errors,[]);
 console.log('PASS TASK104: real bulk paste, dedup, audit jump, compact edits, persistence and QDIAG export');
 await browser.close();
})().catch(e=>{console.error(e.stack);process.exit(1);});