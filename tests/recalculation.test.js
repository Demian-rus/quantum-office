import test from 'node:test';
import assert from 'node:assert/strict';
import {createWorkbookRecalculator,MAX_INCREMENTAL_CHANGES} from '../src/core/recalculation.js';
import {newWorkbook,newSheet,currentSheet,setCell,setStyle,resultOf,displayedValue} from '../src/core/workbook.js';
import {encodeBook,decodeBook} from '../src/core/store.js';

const evaluate=(view,sheet,ref)=>resultOf(sheet,ref,view.raw,view.ctx);
test('a reused UI calculation session survives many redraws, selections and formatting changes',()=>{
 const book=newWorkbook('Нагрузка'),sheet=currentSheet(book);
 setCell(sheet,'A1','12');setCell(sheet,'B1','=A1*2');setCell(sheet,'C1','=B1+3');
 const engine=createWorkbookRecalculator();
 const first=engine.view(book,sheet);
 assert.equal(evaluate(first,sheet,'C1'),27);
 assert.equal(first.ctx.calculation.stats.evaluated,2);
 for(let i=0;i<100;i++){
  const next=engine.view(book,sheet);
  assert.equal(next.ctx.calculation,first.ctx.calculation);
  assert.equal(evaluate(next,sheet,'C1'),27);
 }
 assert.equal(first.ctx.calculation.stats.evaluated,2);
 const old=structuredClone(book);
 setStyle(sheet,'A1',{bold:true});
 assert.equal(engine.reconcile(book,old).mode,'unchanged');
 assert.equal(engine.view(book,sheet).ctx.calculation,first.ctx.calculation);
 assert.equal(engine.stats.created,1);
 assert.ok(engine.stats.reused>=101);
});
test('editing a source invalidates only its transitive graph, not unrelated cached formulas',()=>{
 const book=newWorkbook(),sheet=currentSheet(book);
 [['A1','10'],['B1','=A1*2'],['C1','=B1+1'],['D1','=50+1']].forEach(([ref,value])=>setCell(sheet,ref,value));
 const engine=createWorkbookRecalculator(),first=engine.view(book,sheet);
 assert.equal(evaluate(first,sheet,'C1'),21);
 assert.equal(evaluate(first,sheet,'D1'),51);
 assert.equal(first.ctx.calculation.stats.evaluated,3);
 const before=structuredClone(book);
 setCell(sheet,'A1','20');
 const update=engine.reconcile(book,before);
 assert.equal(update.mode,'incremental');assert.equal(update.changed,1);assert.equal(update.invalidated,3);
 const second=engine.view(book,sheet);
 assert.equal(second.ctx.calculation,first.ctx.calculation);
 assert.equal(evaluate(second,sheet,'D1'),51);
 assert.equal(first.ctx.calculation.stats.evaluated,3);
 assert.equal(evaluate(second,sheet,'C1'),41);
 assert.equal(first.ctx.calculation.stats.evaluated,5);
 assert.equal(engine.stats.created,1);
 assert.equal(displayedValue(sheet,'C1',second.raw,second.ctx),'41');
});
test('cross-sheet changes propagate and lazy IF dependencies switch correctly',()=>{
 const book=newWorkbook(),left=currentSheet(book);left.name='Расчёты';
 const right=newSheet('Учёт оплаты');book.sheets.push(right);
 setCell(right,'A1','10');setCell(right,'B1','50');
 setCell(left,'A1',"=IF('Учёт оплаты'!A1>5,'Учёт оплаты'!B1,7)");
 setCell(left,'A2','=A1+1');
 const engine=createWorkbookRecalculator();
 const first=engine.view(book,left);
 assert.equal(evaluate(first,left,'A2'),51);
 const before=structuredClone(book);setCell(right,'A1','0');
 assert.equal(engine.reconcile(book,before).mode,'incremental');
 const second=engine.view(book,left);
 assert.equal(evaluate(second,left,'A2'),8);
 assert.ok(!second.ctx.calculation.dependencies.get('РАСЧЁТЫ!A1').has('УЧЁТ ОПЛАТЫ!B1'));
 const beforeBranch=structuredClone(book);setCell(right,'B1','99');
 assert.equal(engine.reconcile(book,beforeBranch).invalidated,1);
 assert.equal(evaluate(engine.view(book,left),left,'A2'),8);
 const beforeAgain=structuredClone(book);setCell(right,'A1','10');
 assert.equal(engine.reconcile(book,beforeAgain).mode,'incremental');
 assert.equal(evaluate(engine.view(book,left),left,'A2'),100);
 const other=engine.view(book,right);
 assert.equal(other.ctx.calculation,first.ctx.calculation);
});
test('structural changes and excessive bulk edits fall back safely without stale calculations',()=>{
 const book=newWorkbook(),s=currentSheet(book);
 setCell(s,'A1','1');setCell(s,'B1','=A1+1');
 const engine=createWorkbookRecalculator();
 const original=engine.view(book,s);assert.equal(evaluate(original,s,'B1'),2);
 const beforeName=structuredClone(book);s.name='Данные';
 assert.equal(engine.reconcile(book,beforeName).mode,'reset');
 assert.equal(evaluate(engine.view(book,s),s,'B1'),2);
 const old=engine.view(book,s).ctx.calculation;
 const before=structuredClone(book);
 for(let i=1;i<=MAX_INCREMENTAL_CHANGES+1;i++)setCell(s,'C'+i,String(i));
 const change=engine.reconcile(book,before);
 assert.equal(change.mode,'reset');
 assert.ok(change.changed>MAX_INCREMENTAL_CHANGES);
 const after=engine.view(book,s);
 assert.notEqual(after.ctx.calculation,old);
 assert.equal(evaluate(after,s,'B1'),2);
 assert.equal(engine.stats.created,3);
});
test('Undo/redo workbook replacement, other-book switch and a local midnight rollover invalidate all caches',()=>{
 let day=new Date(2026,9,29);
 const engine=createWorkbookRecalculator(()=>day);
 const book=newWorkbook(),s=currentSheet(book);
 setCell(s,'A1','5');setCell(s,'B1','=A1*3');setCell(s,'C1','=TODAY()');
 const first=engine.view(book,s);assert.equal(evaluate(first,s,'B1'),15);
 const firstDay=evaluate(first,s,'C1');
 assert.equal(firstDay,first.ctx.calculation.today);
 const undo=structuredClone(book);
 const before=structuredClone(book);setCell(s,'A1','9');
 assert.equal(engine.reconcile(book,before).mode,'incremental');
 assert.equal(evaluate(engine.view(book,s),s,'B1'),27);
 const restored=engine.view(undo,undo.sheets[0]);
 assert.equal(evaluate(restored,undo.sheets[0],'B1'),15);
 assert.notEqual(restored.ctx.calculation,first.ctx.calculation);
 day=new Date(2026,9,30);
 const next=engine.view(undo,undo.sheets[0]);
 assert.notEqual(next.ctx.calculation,restored.ctx.calculation);
 assert.equal(evaluate(next,undo.sheets[0],'C1'),firstDay+1);
 const loaded=decodeBook(encodeBook(undo));
 assert.equal(evaluate(engine.view(loaded,loaded.sheets[0]),loaded.sheets[0],'B1'),15);
 assert.equal(engine.stats.created,4);
});
