import test from 'node:test';
import assert from 'node:assert/strict';
import {newWorkbook,currentSheet,setCell,resultOf,displayedValue} from '../src/core/workbook.js';
import {evaluateCell} from '../src/core/formulas.js';
import {encodeBook,decodeBook} from '../src/core/store.js';

function sample(){const b=newWorkbook();const s=currentSheet(b);
[['A1','Данила'],['A2','Мария'],['A3','Данила'],['B1','1500'],['B2','2000'],['B3','1500'],['C1','Оплачено'],['C2','Не оплачено'],['C3','Оплачено']].forEach(([r,v])=>setCell(s,r,v));return {b,s};}
function formula(s,ref,value){setCell(s,ref,value);return resultOf(s,ref);}

test('IF branches are lazy, can return Cyrillic text and use comparison operators',()=>{const {s}=sample();
 assert.equal(formula(s,'D1','=IF(B1>=1500,"Дорого","Дёшево")'),'Дорого');
 assert.equal(formula(s,'D2','=IF(B1<>0;B1/2;1/0)'),750);
 assert.equal(formula(s,'D3','=IF(B1<0,1/0,"Нет")'),'Нет');
 assert.equal(formula(s,'D4','=IF(B1=1500,"Да","Нет")'),'Да');
 assert.equal(formula(s,'D5','=IF(B1>2000,"Да","Нет")'),'Нет');
});
test('logical functions, booleans and concatenation calculate without JavaScript evaluation',()=>{const {s}=sample();
 assert.equal(formula(s,'D1','=AND(B1>=1500,B2>1000)'),true);
 assert.equal(formula(s,'D2','=OR(B1<0,B2>=2000)'),true);
 assert.equal(formula(s,'D3','=NOT(FALSE)'),true);
 assert.equal(formula(s,'D4','=IF(AND(B1>0,NOT(FALSE)),"К оплате: "&B1,"Нет")'),'К оплате: 1500');
 assert.equal(formula(s,'D5','=LEN("Привет")'),6);
});
test('COUNTIF and SUMIF support text, comparisons, wildcard and numbers',()=>{const {s}=sample();
 assert.equal(formula(s,'D1','=COUNTIF(A1:A3,"Данила")'),2);
 assert.equal(formula(s,'D2','=COUNTIF(C1:C3,"Оплачено")'),2);
 assert.equal(formula(s,'D3','=COUNTIF(B1:B3,">=2000")'),1);
 assert.equal(formula(s,'D4','=SUMIF(C1:C3,"Оплачено",B1:B3)'),3000);
 assert.equal(formula(s,'D5','=SUMIF(A1:A3,"Дан*",B1:B3)'),3000);
 assert.equal(formula(s,'D6','=COUNTIF(A1:A3,"*рия")'),1);
});
test('ROUND, ABS, COUNTA, COUNTBLANK, numeric aggregates preserve legacy behavior',()=>{const {s}=sample();
 assert.equal(formula(s,'D1','=ROUND(-1.25,1)'),-1.3);
 assert.equal(formula(s,'D2','=ABS(-19.5)'),19.5);
 assert.equal(formula(s,'D3','=COUNTBLANK(A1:A4)'),1);
 assert.equal(formula(s,'D4','=COUNTA(A1:A4)'),3);
 assert.equal(formula(s,'D5','=SUM(B1:B3)'),5000);
 assert.equal(formula(s,'D6','=AVERAGE(B1:B3)'),5000/3===resultOf(s,'D6')?5000/3:Number((5000/3).toFixed(10)));
 assert.equal(formula(s,'D7','=COUNT(A1:B3)'),3);
});
test('IFERROR catches calculated errors and IF does not evaluate unused branches',()=>{const {s}=sample();
 assert.equal(formula(s,'D1','=IFERROR(1/0,"Ошибка")'),'Ошибка');
 assert.equal(formula(s,'D2','=IFERROR(2+3,"Ошибка")'),5);
 assert.equal(formula(s,'D3','=IF(TRUE,5,1/0)'),5);
 assert.equal(formula(s,'D4','=IFERROR(AVERAGE(A4:A4),"Нет чисел")'),'Нет чисел');
 assert.equal(formula(s,'D5','=IF(FALSE,1/0,10)'),10);
});
test('error codes and malicious formulas do not execute arbitrary code',()=>{const {s}=sample();
 assert.equal(formula(s,'D1','=PROCESS.EXIT(1)'),'#ERROR!');
 assert.equal(formula(s,'D2','=UNSUPPORTED(1)'),'#NAME?');
 assert.equal(formula(s,'D3','=IF(TRUE,1/0,3)'),'#DIV/0!');
 assert.equal(formula(s,'D4','=IF(TRUE,1,3'),'#ERROR!');
 assert.equal(formula(s,'D5','=IF(1,UNKNOWN(1),0)'),'#NAME?');
});
test('formula strings and comparisons survive native book save/load',()=>{const {b,s}=sample();
 formula(s,'D1','=IF(C1="Оплачено","Да","Нет")');
 formula(s,'D2','=SUMIF(C1:C3,"Оплачено",B1:B3)');
 const restored=decodeBook(encodeBook(b));const copied=currentSheet(restored);
 assert.equal(copied.cells.D1.value,'=IF(C1="Оплачено","Да","Нет")');
 assert.equal(resultOf(copied,'D1'),'Да');assert.equal(resultOf(copied,'D2'),3000);
});
