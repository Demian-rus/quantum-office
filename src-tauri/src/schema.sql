CREATE TABLE meta(key TEXT PRIMARY KEY,value TEXT NOT NULL CHECK(json_valid(value)));
CREATE TABLE tasks(id TEXT PRIMARY KEY CHECK(length(id) BETWEEN 1 AND 80),number INTEGER NOT NULL UNIQUE CHECK(number BETWEEN 1 AND 99999),revision INTEGER NOT NULL CHECK(revision>0),created_at TEXT NOT NULL,updated_at TEXT NOT NULL,body TEXT NOT NULL CHECK(json_valid(body)),search_text TEXT NOT NULL,signature TEXT NOT NULL);
CREATE TABLE assets(key TEXT PRIMARY KEY,mime TEXT NOT NULL CHECK(mime IN ('image/png','image/jpeg','image/webp')),sha256 TEXT NOT NULL CHECK(length(sha256)=64),size INTEGER NOT NULL CHECK(size>0),bytes BLOB NOT NULL CHECK(length(bytes)=size),UNIQUE(mime,sha256));
CREATE TABLE task_assets(task_id TEXT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,role TEXT NOT NULL,asset_key TEXT NOT NULL REFERENCES assets(key) ON DELETE RESTRICT,suffix TEXT NOT NULL,PRIMARY KEY(task_id,role));
CREATE INDEX asset_references ON task_assets(asset_key);
CREATE INDEX task_signature ON tasks(signature);
